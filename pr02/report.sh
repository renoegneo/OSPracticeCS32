#!/usr/bin/env bash
# ПР-2, вариант B. Таблица «модуль -> число сообщений» заданного уровня.
# Использование: ./report.sh <каталог> <ERROR|WARN> [--top N]

set -u   # обращение к несуществующей переменной = ошибка, а не тихая пустота

usage() {
    cat >&2 << EOF
Использование: $0 <каталог> <ERROR|WARN> [--top N]

  <каталог>   каталог с файлами *.log
  <уровень>   ERROR или WARN (именно заглавными)
  --top N     показать только N первых модулей (N - целое число >= 1)

Пример: $0 data ERROR --top 3
EOF
}

# Печатает сообщение об ошибке + справку и завершает скрипт с кодом 1.
die() {
    echo "Ошибка: $*" >&2
    usage
    exit 1
}

# --- 1. Проверка аргументов ---------------------------------------------
if (( $# == 0 )); then
    usage
    exit 1
fi
(( $# >= 2 )) || die "нужно указать каталог и уровень"

dir=$1
level=$2
top=0            # 0 = «без ограничения» (ручка: значение по умолчанию для --top)

[[ -d "$dir" ]] || die "каталог '$dir' не существует"
[[ "$level" == "ERROR" || "$level" == "WARN" ]] || die "уровень должен быть ERROR или WARN, получено '$level'"

if (( $# > 2 )); then
    [[ "$3" == "--top" ]] || die "неизвестный аргумент '$3'"
    (( $# == 4 )) || die "после --top нужно указать число N"
    [[ "$4" =~ ^[1-9][0-9]*$ ]] || die "N должно быть целым числом >= 1, получено '$4'"
    top=$4
fi

# --- 2. Список файлов ---------------------------------------------------
shopt -s nullglob          # если *.log ничего не нашёл - массив пустой, а не строка '*.log'
files=("$dir"/*.log)
(( ${#files[@]} > 0 )) || die "в каталоге '$dir' нет файлов *.log"

# --- 3. Подсчёт и вывод -------------------------------------------------
# awk: считает записи нужного уровня по модулям.  $3 - уровень, $4 - module=xxx
# sort: -k1,1nr = по первому столбцу, числа, по убыванию; -k2,2 = при равенстве по имени
# второй awk: оставляет N строк (если задан --top) и рисует таблицу
awk -v lvl="$level" '
    $3 == lvl {
        m = $4
        sub(/^module=/, "", m)
        count[m]++
    }
    END { for (m in count) print count[m], m }
' "${files[@]}" |
sort -k1,1nr -k2,2 |
awk -v limit="$top" '
    BEGIN { printf "%-10s %s\n", "MODULE", "COUNT"; print "--------------------" }
    limit == 0 || NR <= limit { printf "%-10s %d\n", $2, $1 }
    END { if (NR == 0) print "(сообщений такого уровня нет)" }
'
